<?php
// Homepage configuration analysis - all data collected in ONE Drupal bootstrap.
// Run by: scripts/analyze_homepage.sh (through drush_php).
// Output: JSON with homepage_configuration, homepage_type_detection, blocks, page_manager,
//         layout_builder, metadata, page_builder_modules, statistics

$site_config = \Drupal::config('system.site');
$module_handler = \Drupal::moduleHandler();
$entity_type_manager = \Drupal::entityTypeManager();
$node_path_pattern = '/^\/?node\/(\d+)$/';

// Run one part of the analysis. A failing part returns {} and does not break the others.
$section = function (callable $callback) {
  try {
    return $callback();
  }
  catch (\Throwable $e) {
    return new \stdClass();
  }
};

$output = [];

// ---------------------------------------------------------------------------
// Homepage configuration (same shape as: drush config:get system.site page.front)
// ---------------------------------------------------------------------------
$output['homepage_configuration'] = $section(function () use ($site_config) {
  return ['system.site:page.front' => $site_config->get('page.front')];
});

// ---------------------------------------------------------------------------
// Homepage type and details
// ---------------------------------------------------------------------------
$output['homepage_type_detection'] = $section(function () use ($site_config, $entity_type_manager, $node_path_pattern) {
  $front_page = $site_config->get('page.front');

  $result = [
    'configured_path' => $front_page ?: '/node',
    'type' => 'unknown',
    'description' => '',
    'details' => [],
  ];

  if (empty($front_page) || $front_page === '/node') {
    $result['type'] = 'default_promoted';
    $result['description'] = 'Default Drupal homepage showing promoted nodes';

    $count = \Drupal::entityQuery('node')
      ->condition('promote', 1)
      ->condition('status', 1)
      ->accessCheck(FALSE)
      ->count()
      ->execute();
    $result['details']['promoted_nodes_count'] = (int) $count;
  }
  elseif (preg_match($node_path_pattern, $front_page, $matches)) {
    $nid = $matches[1];
    $node = $entity_type_manager->getStorage('node')->load($nid);

    if ($node) {
      $result['type'] = 'static_node';
      $result['description'] = 'Homepage is a specific node/page';
      $result['details'] = [
        'node_id' => (int) $nid,
        'title' => $node->getTitle(),
        'content_type' => $node->bundle(),
        'status' => $node->isPublished() ? 'published' : 'unpublished',
        'created' => date('Y-m-d H:i:s', $node->getCreatedTime()),
        'updated' => date('Y-m-d H:i:s', $node->getChangedTime()),
      ];

      if ($node->hasField('layout_builder__layout')) {
        $layout_enabled = !$node->get('layout_builder__layout')->isEmpty();
        $result['details']['layout_builder_enabled'] = $layout_enabled;

        if ($layout_enabled) {
          $sections = $node->get('layout_builder__layout')->getValue();
          $result['details']['layout_sections_count'] = count($sections);
        }
      }
    }
    else {
      $result['type'] = 'static_node_missing';
      $result['description'] = 'Homepage points to non-existent node';
      $result['details']['node_id'] = (int) $nid;
      $result['details']['error'] = 'Node does not exist';
    }
  }
  else {
    // Check if it's a view
    $is_view = FALSE;
    foreach (\Drupal\views\Views::getAllViews() as $view) {
      if (!$view->status()) {
        continue;
      }
      foreach ($view->get('display') as $display_id => $display) {
        $path = $display['display_options']['path'] ?? NULL;
        $normalized_path = '/' . ltrim((string) $path, '/');
        $normalized_front = '/' . ltrim($front_page, '/');

        if ($path && ($normalized_path === $normalized_front || $path === '<front>' || $path === 'home')) {
          $is_view = TRUE;
          $result['type'] = 'view_based';
          $result['description'] = 'Homepage is generated by a View';
          $result['details'] = [
            'view_id' => $view->id(),
            'view_label' => $view->label(),
            'display_id' => $display_id,
            'display_title' => $display['display_title'] ?? 'Unknown',
            'display_plugin' => $display['display_plugin'] ?? 'unknown',
            'path' => $path,
          ];

          if (isset($display['display_options']['pager']['options']['items_per_page'])) {
            $result['details']['items_per_page'] = (int) $display['display_options']['pager']['options']['items_per_page'];
          }

          if (isset($display['display_options']['filters'])) {
            $exposed_count = 0;
            foreach ($display['display_options']['filters'] as $filter) {
              if (isset($filter['exposed']) && $filter['exposed']) {
                $exposed_count++;
              }
            }
            $result['details']['exposed_filters_count'] = $exposed_count;
          }
          break 2;
        }
      }
    }

    if (!$is_view) {
      // Try to resolve the route
      try {
        $path_to_check = $front_page;
        if (strpos($path_to_check, '/') !== 0) {
          $path_to_check = '/' . $path_to_check;
        }

        $routes = \Drupal::service('router.route_provider')->getRoutesByPattern($path_to_check);

        if ($routes->count() > 0) {
          foreach ($routes as $route_name => $route) {
            $result['type'] = 'custom_route';
            $result['description'] = 'Homepage uses custom route or controller';
            $result['details']['route_name'] = $route_name;
            $result['details']['path'] = $path_to_check;

            // Detect delivery mechanism
            if (strpos($route_name, 'page_manager.') === 0) {
              $result['details']['delivery'] = 'page_manager';
            }
            elseif (strpos($route_name, 'panels.') === 0 || strpos($route_name, 'panel.') === 0) {
              $result['details']['delivery'] = 'panels';
            }
            elseif (strpos($route_name, 'entity.config_pages.') === 0) {
              $result['details']['delivery'] = 'config_pages';
            }
            else {
              $result['details']['delivery'] = 'custom_controller';
            }

            $controller = $route->getDefault('_controller');
            $form = $route->getDefault('_form');
            $entity_view = $route->getDefault('_entity_view');

            if ($controller) {
              $result['details']['controller'] = $controller;
            }
            if ($form) {
              $result['details']['form'] = $form;
            }
            if ($entity_view) {
              $result['details']['entity_view'] = $entity_view;
            }
            break;
          }
        }
        else {
          $result['type'] = 'unknown';
          $result['description'] = 'Could not resolve route';
          $result['details']['error'] = 'Route not found for path: ' . $front_page;
        }
      }
      catch (\Exception $e) {
        $result['type'] = 'error';
        $result['description'] = 'Error resolving route';
        $result['details']['error'] = $e->getMessage();
      }
    }
  }

  return $result;
});

// ---------------------------------------------------------------------------
// Blocks of the default theme (by region)
// ---------------------------------------------------------------------------
$output['blocks'] = $section(function () use ($entity_type_manager) {
  $theme = \Drupal::config('system.theme')->get('default');
  $blocks = $entity_type_manager->getStorage('block')->loadByProperties(['theme' => $theme]);

  $result = [
    'theme' => $theme,
    'total_active_blocks' => 0,
    'regions' => [],
  ];

  foreach ($blocks as $block) {
    if (!$block->status()) {
      continue;
    }
    $result['total_active_blocks']++;
    $region = $block->getRegion();

    $plugin_id = $block->getPluginId();
    $plugin_type = 'other';
    if (strpos($plugin_id, 'block_content:') === 0) {
      $plugin_type = 'custom_block';
    }
    elseif (strpos($plugin_id, 'system_') === 0) {
      $plugin_type = 'system';
    }
    elseif (strpos($plugin_id, 'views_block:') === 0) {
      $plugin_type = 'views';
    }
    elseif (strpos($plugin_id, 'menu_block:') === 0) {
      $plugin_type = 'menu';
    }

    $result['regions'][$region][] = [
      'id' => $block->id(),
      'label' => $block->label(),
      'plugin_id' => $plugin_id,
      'plugin_type' => $plugin_type,
      'weight' => $block->getWeight(),
    ];
  }

  // Sort blocks by weight within each region
  foreach ($result['regions'] as $region => $blocks_list) {
    usort($blocks_list, function ($a, $b) {
      return $a['weight'] <=> $b['weight'];
    });
    $result['regions'][$region] = $blocks_list;
  }

  return $result;
});

// ---------------------------------------------------------------------------
// Page Manager
// ---------------------------------------------------------------------------
$output['page_manager'] = $section(function () use ($module_handler, $entity_type_manager) {
  $result = [
    'module_enabled' => FALSE,
    'pages' => [],
    'homepage_override' => FALSE,
  ];

  if ($module_handler->moduleExists('page_manager')) {
    $result['module_enabled'] = TRUE;

    foreach ($entity_type_manager->getStorage('page')->loadMultiple() as $page) {
      $path = $page->getPath();
      $page_info = [
        'id' => $page->id(),
        'label' => $page->label(),
        'path' => $path,
        'is_homepage' => in_array($path, ['/', '<front>', '/node']),
      ];
      if ($page_info['is_homepage']) {
        $result['homepage_override'] = TRUE;
      }
      $result['pages'][] = $page_info;
    }
  }

  return $result;
});

// ---------------------------------------------------------------------------
// Layout Builder
// ---------------------------------------------------------------------------
$output['layout_builder'] = $section(function () use ($module_handler, $site_config, $entity_type_manager, $node_path_pattern) {
  $result = [
    'module_enabled' => FALSE,
    'homepage_uses_layout_builder' => FALSE,
    'details' => [],
  ];

  $layout_builder_enabled = $module_handler->moduleExists('layout_builder');
  $result['module_enabled'] = $layout_builder_enabled;

  if ($layout_builder_enabled) {
    $front_page = (string) $site_config->get('page.front');

    if (preg_match($node_path_pattern, $front_page, $matches)) {
      $node = $entity_type_manager->getStorage('node')->load($matches[1]);

      if ($node && $node->hasField('layout_builder__layout') && !$node->get('layout_builder__layout')->isEmpty()) {
        $result['homepage_uses_layout_builder'] = TRUE;
        $result['details'] = [
          'layout_type' => 'custom_per_node',
          'sections_count' => count($node->get('layout_builder__layout')->getValue()),
        ];
      }
    }
  }

  return $result;
});

// ---------------------------------------------------------------------------
// Metadata
// ---------------------------------------------------------------------------
$output['metadata'] = $section(function () use ($site_config) {
  $result = [
    'site_name' => $site_config->get('name'),
    'site_slogan' => $site_config->get('slogan') ?: '',
    'site_email' => $site_config->get('mail'),
    'page_403' => $site_config->get('page.403') ?: '/user/login',
    'page_404' => $site_config->get('page.404') ?: '',
  ];

  // Path alias for homepage
  $front_page = $site_config->get('page.front') ?: '/node';
  $alias = \Drupal::service('path_alias.manager')->getAliasByPath($front_page);

  $result['homepage_system_path'] = $front_page;
  $result['homepage_alias'] = $alias !== $front_page ? $alias : '';

  try {
    $result['homepage_full_url'] = \Drupal::request()->getSchemeAndHttpHost() . $alias;
  }
  catch (\Exception $e) {
    $result['homepage_full_url'] = '';
  }

  return $result;
});

// ---------------------------------------------------------------------------
// Page builder modules
// ---------------------------------------------------------------------------
$output['page_builder_modules'] = $section(function () use ($module_handler) {
  $modules_to_check = [
    'layout_builder' => 'Layout Builder',
    'page_manager' => 'Page Manager',
    'panels' => 'Panels',
    'panelizer' => 'Panelizer',
    'paragraphs' => 'Paragraphs',
    'block_content' => 'Custom Block Library',
  ];

  $result = [];
  foreach ($modules_to_check as $module_name => $module_label) {
    $result[$module_name] = [
      'label' => $module_label,
      'installed' => $module_handler->moduleExists($module_name),
    ];
  }
  return $result;
});

// ---------------------------------------------------------------------------
// Statistics
// ---------------------------------------------------------------------------
$output['statistics'] = $section(function () use ($site_config, $module_handler, $entity_type_manager, $node_path_pattern) {
  $front_page = $site_config->get('page.front') ?: '/node';

  $type = 'unknown';
  if (empty($front_page) || $front_page === '/node') {
    $type = 'default_promoted';
  }
  elseif (preg_match($node_path_pattern, $front_page)) {
    $type = 'static_node';
  }
  else {
    foreach (\Drupal\views\Views::getAllViews() as $view) {
      if (!$view->status()) {
        continue;
      }
      foreach ($view->get('display') as $display) {
        $path = $display['display_options']['path'] ?? NULL;
        $normalized_path = '/' . ltrim((string) $path, '/');
        $normalized_front = '/' . ltrim($front_page, '/');
        if ($path && ($normalized_path === $normalized_front || $path === '<front>')) {
          $type = 'view_based';
          break 2;
        }
      }
    }
    if ($type === 'unknown') {
      $type = 'custom_route';
    }
  }

  $theme = \Drupal::config('system.theme')->get('default');
  $active_count = 0;
  foreach ($entity_type_manager->getStorage('block')->loadByProperties(['theme' => $theme]) as $block) {
    if ($block->status()) {
      $active_count++;
    }
  }

  return [
    'homepage_path' => $front_page,
    'homepage_type' => $type,
    'active_blocks_count' => $active_count,
    'layout_builder_installed' => $module_handler->moduleExists('layout_builder'),
    'page_manager_installed' => $module_handler->moduleExists('page_manager'),
    'panels_installed' => $module_handler->moduleExists('panels'),
  ];
});

echo json_encode($output, JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE | JSON_INVALID_UTF8_SUBSTITUTE | JSON_PARTIAL_OUTPUT_ON_ERROR);
